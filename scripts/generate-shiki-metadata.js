/**
 * Generate the Shiki language and theme metadata used by the code editor.
 *
 * Shiki’s own `bundledLanguagesInfo` / `bundledThemesInfo` carry a lazy `import()` thunk per entry.
 * Importing them at runtime would make every bundler pull in the full ~10 MB grammar set, which
 * a single-file bundle (our main consumer, Sveltia CMS) would inline wholesale. Stripping them
 * leaves just the few kilobytes of metadata the switcher and the alias normalizer actually need;
 * the grammars themselves are fetched on demand at runtime instead.
 * @see https://github.com/sveltia/sveltia-cms/issues/587
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { bundledLanguagesInfo } from 'shiki/langs';
import { bundledThemesInfo } from 'shiki/themes';

/**
 * Read a package’s version from `node_modules`.
 * @param {string} name Package name.
 * @returns {string} Exact version.
 */
const getVersion = (name) =>
  JSON.parse(readFileSync(new URL(`../node_modules/${name}/package.json`, import.meta.url), 'utf8'))
    .version;

const shikiVersion = getVersion('shiki');

const { version: uiVersion } = JSON.parse(
  readFileSync(new URL('../package.json', import.meta.url), 'utf8'),
);

const languages = bundledLanguagesInfo
  .map(({ id, name, aliases }) => (aliases?.length ? { id, name, aliases } : { id, name }))
  .sort((a, b) => a.name.localeCompare(b.name));

const themes = bundledThemesInfo.map(({ id, displayName, type }) => ({ id, displayName, type }));

const content = `// Generated by \`scripts/generate-shiki-metadata.js\`. DO NOT EDIT.

/**
 * Version of Shiki whose grammars and themes are fetched at runtime. Must stay in sync with the
 * version bundled into \`dist/shiki-engine.js\`, because grammar and theme payloads are only
 * guaranteed to be compatible with the matching engine.
 */
export const SHIKI_VERSION = ${JSON.stringify(shikiVersion)};

/**
 * Version of this package, used to resolve the prebuilt Shiki engine chunk from a CDN.
 */
export const UI_VERSION = ${JSON.stringify(uiVersion)};

/**
 * Available syntax highlighting languages, sorted by display name.
 * @type {{ id: string, name: string, aliases?: string[] }[]}
 */
export const LANGUAGES = ${JSON.stringify(languages)};

/**
 * Available syntax highlighting themes.
 * @type {{ id: string, displayName: string, type: string }[]}
 */
export const THEMES = ${JSON.stringify(themes)};
`;

const outPath = new URL('../src/lib/components/text-editor/shiki/generated.js', import.meta.url);

writeFileSync(outPath, content);

// eslint-disable-next-line no-console
console.log(
  `Generated ${languages.length} languages and ${themes.length} themes ` +
    `for shiki@${shikiVersion} (@sveltia/ui@${uiVersion}).`,
);
