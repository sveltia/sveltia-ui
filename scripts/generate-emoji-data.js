/**
 * Generate the emoji list used by the emoji autocomplete.
 *
 * The source is `iamcal/emoji-data`, the dataset behind Slack’s and Discord’s emoji shortcodes, so
 * `:pray:` and `:tada:` mean here what they mean everywhere else. Its `emoji.json` is 1.3 MB of
 * spritesheet coordinates, legacy carrier encodings and skin tone variations, none of which a
 * shortcode search needs, so this keeps the character, the shortcodes and a few searchable words
 * from the Unicode name, and writes them out as one line per emoji — around 45 KB, small enough to
 * ship in the bundle rather than fetch at runtime.
 *
 * This is deliberately left out of `npm run build`: it reaches for the network, and the dataset
 * only moves when Unicode does. Run it by hand when there is a new release, and commit the result.
 * @see https://github.com/iamcal/emoji-data
 */

import { writeFileSync } from 'node:fs';

/** Release of the dataset to generate from. */
const VERSION = '16.0.0';
const SOURCE_URL = `https://raw.githubusercontent.com/iamcal/emoji-data/v${VERSION}/emoji.json`;
/**
 * Category holding the skin tone modifiers, which are not emojis in their own right.
 */
const COMPONENT_CATEGORY = 'Component';
/**
 * Words dropped from the Unicode names, because nobody searches by them and every one of them
 * spans hundreds of emojis.
 */
const STOP_WORDS = new Set(['a', 'an', 'and', 'for', 'in', 'of', 'on', 'or', 'the', 'to', 'with']);
/**
 * Characters a shortcode may be made up of, which is what {@link EMOJI_TRIGGER_REGEX} accepts.
 */
const SHORTCODE_REGEX = /^[a-z0-9_+-]+$/;

/**
 * Turn a `unified` code point sequence into the character it denotes.
 * @param {string} unified Hyphen-separated hexadecimal code points, e.g. `1F1E8-1F1E6`.
 * @returns {string} Emoji character.
 */
const getEmojiCharacter = (unified) =>
  unified
    .split('-')
    .map((codePoint) => String.fromCodePoint(Number.parseInt(codePoint, 16)))
    .join('');

/**
 * Get the searchable words in an emoji’s Unicode name that its shortcodes don’t already carry.
 *
 * The shortcodes are what the user is expected to type, but they’re often an abbreviation the name
 * spells out: 🇨🇦 is `flag-ca`, and only `Canada Flag` says which country that is. Anything the
 * shortcodes already contain is left out, since it would only be searched for twice.
 * @param {{ name: string, short_names: string[] }} entry Raw emoji entry.
 * @returns {string[]} Extra keywords, in the order the name spells them out.
 */
const getExtraKeywords = ({ name, short_names: shortNames }) => {
  // Both the whole shortcodes and their words, because a name can spell a hyphenated shortcode out
  // as a single word, as `X-RAY` does
  const known = new Set(shortNames.flatMap((shortName) => [shortName, ...shortName.split(/[-_]/)]));

  return [
    ...new Set(
      name
        .toLowerCase()
        .split(/[^a-z0-9+-]+/)
        .filter((word) => word && !STOP_WORDS.has(word) && !known.has(word)),
    ),
  ];
};

const response = await fetch(SOURCE_URL);

if (!response.ok) {
  throw new Error(`Failed to fetch ${SOURCE_URL}: ${response.status}`);
}

/** @type {any[]} */
const rawEntries = await response.json();

const entries = rawEntries
  .filter(({ category }) => category !== COMPONENT_CATEGORY)
  .sort((a, b) => a.sort_order - b.sort_order)
  .map((entry) => {
    const shortNames = entry.short_names;
    const invalid = shortNames.find((/** @type {string} */ n) => !SHORTCODE_REGEX.test(n));

    if (invalid) {
      throw new Error(`Shortcode cannot be typed as a query: ${invalid}`);
    }

    return [
      getEmojiCharacter(entry.unified),
      shortNames.join(' '),
      getExtraKeywords(entry).join(' '),
    ]
      .filter(Boolean)
      .join('\t');
  });

const data = entries.join('\n');

// The list goes into a template literal, which only these could break out of
if (/[`\\]|\$\{/.test(data)) {
  throw new Error('Emoji data contains a character that cannot be written as a template literal');
}

const content = `// Generated by \`scripts/generate-emoji-data.js\`. DO NOT EDIT.

/**
 * Emoji list from \`emoji-data\` v${VERSION}, in the Unicode order the dataset publishes.
 *
 * One line per emoji, made up of tab-separated fields: the emoji character, its shortcodes, and any
 * further searchable words taken from its Unicode name. Multiple shortcodes or keywords within a
 * field are separated by a space, and the last field is left out when there are no extra keywords.
 * The first shortcode is the canonical one, the one shown alongside the emoji in the suggestions.
 *
 * It’s a single string rather than an object so that it costs one line per emoji in the bundle
 * instead of a few hundred bytes of punctuation, and so that nothing is parsed until the first
 * shortcode is actually typed.
 * @see https://github.com/iamcal/emoji-data
 */
export const EMOJI_DATA = \`${data}\`;
`;

writeFileSync(new URL('../src/lib/components/emoji/generated.js', import.meta.url), content);

// eslint-disable-next-line no-console
console.log(`Generated ${entries.length} emojis from emoji-data v${VERSION}.`);
